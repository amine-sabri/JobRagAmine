#!/usr/bin/env python
"""Compare the retrievers on probe queries, before the evaluation set exists.

For a query naming an exact technology, the share of the top-k chunks that
actually contain that term is measurable without any labelling. It is the
sharpest available test of the claim that vector search is weak on exact
tokens — and of whether hybrid retrieval repairs it.

Usage:
    python scripts/search_probe.py [--k 5]
"""

import argparse
import json
import sys
import time
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from jobrag.embed import get_embedder  # noqa: E402
from jobrag.report import inject_into_file, markdown_table  # noqa: E402
from jobrag.retrieve.fusion import fuse_hits  # noqa: E402
from jobrag.retrieve.keyword import search_chunks as keyword_search  # noqa: E402
from jobrag.retrieve.vector import search_chunks as vector_search  # noqa: E402

# (query, the term that must literally appear — None for a semantic probe)
PROBES: list[tuple[str, str | None]] = [
    ("Kubernetes", "kubernetes"),
    ("FastAPI", "fastapi"),
    ("Terraform", "terraform"),
    ("PyTorch", "pytorch"),
    ("Quelles offres demandent Kubernetes à Paris ?", "kubernetes"),
    ("offres pour un profil Python junior", "python"),
    ("télétravail complet", None),
    ("poste d'ingénieur en intelligence artificielle", None),
]


def fold(text: str) -> str:
    decomposed = unicodedata.normalize("NFKD", (text or "").lower())
    return "".join(ch for ch in decomposed if not unicodedata.combining(ch))


def run(mode: str, query: str, k: int, embedder, depth: int):
    started = time.perf_counter()
    if mode == "keyword":
        hits = keyword_search(query, k=k)["results"]
    elif mode == "vector":
        hits = vector_search(query, embedder, k=k)["results"]
    else:
        hits = fuse_hits(
            [
                vector_search(query, embedder, k=depth)["results"],
                keyword_search(query, k=depth)["results"],
            ],
            limit=k,
        )
    return hits, (time.perf_counter() - started) * 1000


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--k", type=int, default=5)
    parser.add_argument("--depth", type=int, default=20)
    parser.add_argument("--results", default="eval/results", type=Path)
    parser.add_argument("--readme", default="README.md", type=Path)
    parser.add_argument("--no-readme", action="store_true")
    args = parser.parse_args()

    embedder = get_embedder(threads=4)
    print(f"loading {embedder.model_name} …", flush=True)
    dimensions = embedder.dimension  # load before timing anything
    print(f"  {dimensions} dimensions", flush=True)

    modes = ("vector", "keyword", "hybrid")
    rows = []
    detail: dict[str, dict] = {}
    for query, term in PROBES:
        line = [query if len(query) < 46 else query[:43] + "…"]
        detail[query] = {"term": term, "modes": {}}
        for mode in modes:
            hits, ms = run(mode, query, args.k, embedder, args.depth)
            if term:
                contains = sum(1 for hit in hits if term in fold(hit["text"]))
                line.append(f"{contains}/{len(hits)}")
            else:
                line.append(f"{len(hits)} hits")
            line.append(f"{ms:.0f}")
            detail[query]["modes"][mode] = {
                "ms": round(ms, 1),
                "contains_term": (
                    sum(1 for hit in hits if term in fold(hit["text"])) if term else None
                ),
                "top": [
                    {
                        "title": hit["title"],
                        "company": hit["company"],
                        "city": hit["city"],
                        "score": hit.get("score", hit.get("rrf_score")),
                    }
                    for hit in hits[:3]
                ],
            }
        rows.append(line)
        print("  " + " | ".join(str(cell) for cell in line), flush=True)

    headers = ["query"]
    for mode in modes:
        headers += [f"{mode}: term in top-{args.k}", f"{mode} ms"]
    table = markdown_table(headers, rows)

    args.results.mkdir(parents=True, exist_ok=True)
    (args.results / "search_probe.json").write_text(
        json.dumps(detail, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    md = f"<!-- generated by: `python scripts/search_probe.py --k {args.k}` -->\n\n{table}\n"
    (args.results / "search_probe.md").write_text(md, encoding="utf-8")
    if not args.no_readme:
        inject_into_file(args.readme, "search-probe", md)
    print("\n" + table)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
